// Embeds the pdfium and duke-sheets wasm binaries into server-side TS modules
// so the files.pdf_wasm and files.xlsx_wasm RPCs can serve them without
// touching the filesystem at runtime.
//
// The daemon evaluates plugin server bundles with globalThis.eval in its
// worker process — __filename and import.meta.url carry nothing usable, so a
// runtime path into node_modules can never resolve. Base64 in the bundle is
// the only self-contained option.
import { readFileSync, writeFileSync, mkdirSync } from "fs";

mkdirSync("./server/generated", { recursive: true });

function inlineWasm({ wasmPath, outputPath, exportName, label, rpcName }) {
  const wasm = readFileSync(wasmPath);
  const base64 = wasm.toString("base64");
  const sizeKb = Math.round(wasm.length / 1024);

  writeFileSync(
    outputPath,
    `// Auto-generated by scripts/inline-wasm.js — DO NOT EDIT.
// ${label} (${sizeKb}KB) served by the ${rpcName} RPC.
export const ${exportName} = ${JSON.stringify(base64)};
`
  );

  console.log(`✓ Generated ${outputPath} from ${wasmPath} (${sizeKb}KB)`);
}

inlineWasm({
  wasmPath: "./node_modules/@embedpdf/pdfium/dist/pdfium.wasm",
  outputPath: "./server/generated/pdfium-wasm.ts",
  exportName: "pdfiumWasmBase64",
  label: "pdfium wasm",
  rpcName: "files.pdf_wasm",
});

inlineWasm({
  wasmPath: "./node_modules/@dukelib/sheets-wasm/duke_sheets_wasm_bg.wasm",
  outputPath: "./server/generated/xlsx-wasm.ts",
  exportName: "xlsxWasmBase64",
  label: "duke-sheets wasm",
  rpcName: "files.xlsx_wasm",
});
