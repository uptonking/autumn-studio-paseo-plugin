// Embeds the pdfium wasm binary into a server-side TS module so the
// files.pdf_wasm RPC can serve it without touching the filesystem.
//
// The daemon evaluates plugin server bundles with globalThis.eval in its
// worker process — __filename and import.meta.url carry nothing usable, so a
// runtime path into node_modules can never resolve. Base64 in the bundle is
// the only self-contained option.
import { readFileSync, writeFileSync, mkdirSync } from "fs";

const wasmPath = "./node_modules/@embedpdf/pdfium/dist/pdfium.wasm";
const outputPath = "./server/generated/pdfium-wasm.ts";

const wasm = readFileSync(wasmPath);
mkdirSync("./server/generated", { recursive: true });

const base64 = wasm.toString("base64");
// Chunk the literal so no single line gets absurdly long.
const lines = base64.match(/.{1,120}/g) ?? [];

writeFileSync(
  outputPath,
  `// Auto-generated by scripts/inline-wasm.js — DO NOT EDIT.
// pdfium wasm (${Math.round(wasm.length / 1024)}KB) served by the files.pdf_wasm RPC.
export const pdfiumWasmBase64 = [
${lines.map((line) => `  "${line}",`).join("\n")}
].join("");
`
);

console.log(`✓ Generated ${outputPath} from ${wasmPath} (${Math.round(wasm.length / 1024)}KB)`);
