import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname } from "path";

const css = readFileSync("./dist/tailwind.css", "utf-8");
const outputPath = "./client/generated/tailwind-styles.ts";

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Auto-generated by scripts/inline-css.js - DO NOT EDIT\nexport const tailwindCss = ${JSON.stringify(css)};\n`
);

console.log(`✓ Generated ${outputPath} (${css.length} bytes)`);
